export function hasPermission(role: SystemRole, permission: Permission): boolean {
  if (role === "SUPER_ADMIN") return true;
  const permissions = ROLE_DEFAULT_PERMISSIONS[role] || [];
  return permissions.includes(permission);
}

export function isRoleAtLeast(role: SystemRole, minimumRole: SystemRole): boolean {
  const currentLevel = SYSTEM_ROLES[role]?.level ?? 0;
  const minLevel = SYSTEM_ROLES[minimumRole]?.level ?? 0;
  return currentLevel >= minLevel;
}
